#!/usr/bin/env python3
"""Generate the C++ action table from the verified 772-action spec.

The runtime table is generated, never hand-edited. Input is the artifact
produced by ``tools/analysis/action_specs.py`` from the shipped ``nwscript.nss``
and the verified action addresses. The generated header is committed so an
engine build does not depend on the artifact tree.

    python tools/analysis/gen_cpp_action_table.py \
      --specs artifacts/lanes/s2-01-engine-map/action_specs.json \
      --out engine/src/script/ActionTable.inc

Every row carries only the public NWScript signature facts (id, name, parameter
kinds and return kind), not decompiled program text.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

RETURN_KINDS = {
    "void": "Void",
    "int": "Int",
    "float": "Float",
    "string": "String",
    "object": "Object",
    "vector": "Vector",
    "effect": "Engine",
    "event": "Engine",
    "location": "Engine",
    "talent": "Engine",
}

PARAM_KINDS = {
    "int": "Int",
    "INT": "Int",
    "float": "Float",
    "string": "String",
    "object": "Object",
    "OBJECT_ID": "Object",
    "vector": "Vector",
    "effect": "Engine",
    "event": "Engine",
    "location": "Engine",
    "talent": "Engine",
    "action": "Action",
}

MAX_PARAMS = 12


def build(specs: dict) -> str:
    actions = sorted(specs["actions"], key=lambda a: a["id"])
    ids = [a["id"] for a in actions]
    if ids != list(range(772)):
        raise SystemExit("action ids are not the verified contiguous 0..771 range")
    if len({a["name"] for a in actions}) != 772:
        raise SystemExit("action names are not unique")

    lines = [
        "// Generated by tools/analysis/gen_cpp_action_table.py. Do not edit.",
        "// Source: verified 772-action spec (nwscript.nss + handler addresses).",
        "// Schema: ACTION(id, name, return, param_count, param0, ..., param11)",
        "// Clang-format off",
    ]
    for action in actions:
        ret = RETURN_KINDS.get(action["return"])
        if ret is None:
            raise SystemExit(f"action {action['id']} has unknown return {action['return']!r}")
        params = action["params"]
        if len(params) > MAX_PARAMS:
            raise SystemExit(f"action {action['id']} has {len(params)} params")
        kinds = []
        for param in params:
            kind = PARAM_KINDS.get(param["type"])
            if kind is None:
                raise SystemExit(f"action {action['id']} has unknown param {param['type']!r}")
            kinds.append(kind)
        padded = kinds + ["None"] * (MAX_PARAMS - len(kinds))
        lines.append(
            'ACTION(%d, "%s", %s, %d, %s)'
            % (action["id"], action["name"], ret, len(kinds), ", ".join(padded))
        )
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--specs", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    payload = Path(args.specs).read_bytes()
    specs = json.loads(payload)
    text = build(specs)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(
        json.dumps(
            {
                "schema": "kotor.action-table.cpp/1",
                "actions": len(specs["actions"]),
                "output": str(out),
                "output_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                "source_sha256": hashlib.sha256(payload).hexdigest(),
                "source_build_sha256": specs.get("build_sha256"),
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
